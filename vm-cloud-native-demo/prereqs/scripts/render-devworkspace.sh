#!/usr/bin/env bash
# Render the Dev Spaces workspace that the prerequisite Argo CD Application applies.
#
# The workspace is a DevWorkspace CR, so the editor must be part of its template:
# Dev Spaces' dashboard normally merges the editor devfile from the cluster's
# `editors-definitions` ConfigMap when a human creates a workspace. GitOps cannot
# do that, so the editor definition is vendored in editor-che-code.yaml and
# merged here. Refresh the stub after a Dev Spaces upgrade:
#
#   ./prereqs/scripts/render-devworkspace.sh --refresh-editor
#
# Usage: render-devworkspace.sh [--stdout|--check|--refresh-editor]
set -euo pipefail
DEMO_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
EDITOR="$DEMO_DIR/prereqs/devspace/editor-che-code.yaml"
MANIFEST="$DEMO_DIR/prereqs/devspace/devworkspace.yaml"
DEVSPACES_NAMESPACE=${DEVSPACES_NAMESPACE:-openshift-devspaces}
export DEMO_DIR EDITOR MANIFEST DEVSPACES_NAMESPACE
export DEVSPACE_NAME=${DEVSPACE_NAME:-rocket-ramen}
export DEVSPACE_GIT_REF=${DEVSPACE_GIT_REF:-main}
export DEVSPACE_API_URL=${DEVSPACE_API_URL:-http://orders-api.rocket-ramen.svc.cluster.local:8080}

mode=${1:---write}
case "$mode" in --write|--stdout|--check|--refresh-editor) ;; *) echo 'Usage: render-devworkspace.sh [--stdout|--check|--refresh-editor]' >&2; exit 2 ;; esac

if [[ "$mode" == --refresh-editor ]]; then
  command -v oc >/dev/null || { echo 'oc is required to refresh the editor definition.' >&2; exit 1; }
  oc get configmap editors-definitions -n "$DEVSPACES_NAMESPACE" -o json | ruby -rjson -ryaml -e '
    data = JSON.parse(STDIN.read).fetch("data")
    editor = YAML.load(data.fetch("che-code.yaml"))
    stub = {
      "commands" => editor.fetch("commands"),
      "components" => editor.fetch("components"),
      "events" => editor["events"]
    }.reject { |_, value| value.nil? || value.empty? }
    header = <<~YAML
      # Vendored from the #{ENV.fetch("DEVSPACES_NAMESPACE")} editors-definitions ConfigMap
      # (key: che-code.yaml), minus metadata and icons. The Dev Spaces dashboard
      # normally merges this at workspace creation; GitOps needs it inline.
      # Refresh with: ./prereqs/scripts/render-devworkspace.sh --refresh-editor
    YAML
    File.write(ENV.fetch("EDITOR"), header + YAML.dump(stub))
  '
  printf 'Wrote %s\n' "${EDITOR#$DEMO_DIR/}"
  exec "$0" --write
fi

render() {
  ruby -ryaml -e '
    root = ENV.fetch("DEMO_DIR")
    devfile = YAML.load_file(File.join(root, "devfile.yaml"))
    editor = YAML.load_file(ENV.fetch("EDITOR"))

    ref = ENV.fetch("DEVSPACE_GIT_REF")
    devfile.fetch("projects").each do |project|
      git = project["git"] or next
      git["checkoutFrom"] = { "revision" => ref }
    end

    api_url = ENV.fetch("DEVSPACE_API_URL")
    node = devfile.fetch("components").find { |c| c["name"] == "node" } or abort "devfile has no node component"
    env = (node["container"]["env"] ||= [])
    env.reject! { |entry| entry["name"] == "API_URL" }
    env << { "name" => "API_URL", "value" => api_url }

    template = {
      "projects" => devfile.fetch("projects"),
      "components" => devfile.fetch("components") + editor.fetch("components"),
      "commands" => devfile.fetch("commands") + editor.fetch("commands")
    }
    events = editor["events"]
    template["events"] = events if events && !events.empty?

    workspace = {
      "apiVersion" => "workspace.devfile.io/v1alpha2",
      "kind" => "DevWorkspace",
      "metadata" => {
        "name" => ENV.fetch("DEVSPACE_NAME"),
        "annotations" => {
          "argocd.argoproj.io/sync-options" => "SkipDryRunOnMissingResource=true",
          "demo.redhat.com/purpose" => "Prerequisite Dev Spaces workspace for the Rocket Ramen presentation"
        }
      },
      "spec" => { "started" => true, "template" => template }
    }
    print "# Generated by ./prereqs/scripts/render-devworkspace.sh. Edit devfile.yaml or editor-che-code.yaml.\n"
    print YAML.dump(workspace)
  '
}

case "$mode" in
  --stdout) render ;;
  --write)
    render >"$MANIFEST.tmp"
    mv "$MANIFEST.tmp" "$MANIFEST"
    printf 'Wrote %s\n' "${MANIFEST#$DEMO_DIR/}"
    ;;
  --check)
    if ! diff -u "$MANIFEST" <(render) >/tmp/ramen-devworkspace.diff; then
      printf 'DevWorkspace manifest is stale; run ./prereqs/scripts/render-devworkspace.sh\n' >&2
      sed -n '1,40p' /tmp/ramen-devworkspace.diff >&2
      exit 1
    fi
    printf 'DevWorkspace manifest matches devfile.yaml and the editor stub.\n'
    ;;
esac
